import {readFileSync,writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
const [directory,revision] = process.argv.slice(2);
if (!directory || !/^[a-f0-9]{40}$/.test(revision || '')) throw new Error('Usage: node scripts/import-sketchup-extension.mjs /path/to/extension/dist <verified-source-commit>');
const metadata=JSON.parse(readFileSync(resolve(directory,'extension.json'),'utf8'));
if (!/^from-trees-cabinet-designer-[0-9.]+\.rbz$/.test(metadata.filename)) throw new Error('Invalid installer filename');
const bytes=readFileSync(resolve(directory,metadata.filename));
if (createHash('sha256').update(bytes).digest('hex')!==metadata.sha256) throw new Error('Installer checksum mismatch');
const bundle={...metadata,sourceRepository:'https://github.com/noahpeters/from-trees-sketchup',sourceRevision:revision,data:bytes.toString('base64')};
writeFileSync(new URL('../apps/api/src/assets/sketchupExtension.ts',import.meta.url),'// Generated by scripts/import-sketchup-extension.mjs from the reviewed extension repository.\nexport const SKETCHUP_EXTENSION = '+JSON.stringify(bundle)+' as const;\n');
